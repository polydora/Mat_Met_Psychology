# ========== ЗАГРУЗКА ДАННЫХ ==========
data(iris)

#Оставляю только versicolor и смотрю данные
iris_versicolor <- iris[iris$Species == "versicolor", ]
head(iris_versicolor)


#Создаю график, что б понять как визуально выглядят данные
plot(
  iris_versicolor$Petal.Length,
  iris_versicolor$Sepal.Length,
  xlab = "Длина лепестка (Petal.Length)",
  ylab = "Длина чашелистика (Sepal.Length)",
  main = "Versicolor: Sepal.Length vs Petal.Length",
  pch = 19,
  col = "purple"
)


# ЧТО ВИЖУ НА ГРАФИКЕ:
#Точки идут слева-снизу вправо-вверх — значит чем длиннее лепесток, тем длиннее чашелистик. Связь положительная: если одна переменная растёт, вторая тоже.
#Точки лежат довольно кучно, без явных выбросов — похоже связь линейная.



# ========== 1. ЛИНЕЙНАЯ МОДЕЛЬ ==========
model <- lm(Sepal.Length ~ Petal.Length, data = iris_versicolor)
#Sepal.Length — отклик (то, что предсказываем)
#Petal.Length — предиктор (то, чем объясняем)

#Проверяю результаты
cat("=== РЕЗУЛЬТАТЫ ЛИНЕЙНОЙ МОДЕЛИ ===\n")
summary(model)
#Смотрим на p-value для Petal.Length. Если p-value < 0.05 — связь ЗНАЧИМА


# ЧТО ВИЖУ В РЕЗУЛЬТАТАХ:
#Intercept = 2.41 — это просто точка на оси Y, где линия пересекает её. В реальности лепесток длиной 0 см не бывает, это чисто для математики.
#Petal.Length = 0.83 — это наклон линии. Увеличиваю лепесток на 1 см — чашелистик в среднем становится на 0.83 см длиннее.
#Multiple R-squared = 0.57 — модель объясняет 57% того, почему чашелистики разной длины. Больше половины, неплохо. Остальное — влажность, освещение, возраст и т д.
#p-value для Petal.Length = 2.59e-10 — это очень-очень мало, сильно меньше 0.05. Значит связь есть, это не случайность.



# ========== 2. ПРОВЕРКА ОСТАТКОВ ==========
cat("\n=== ПРОВЕРКА ОСТАТКОВ ===\n")

#Нормальность остатков
residuals <- residuals(model)
shapiro_test <- shapiro.test(residuals)
cat("Тест Шапиро-Уилка на нормальность остатков:\n")
cat("p-value =", shapiro_test$p.value, "\n")
if (shapiro_test$p.value > 0.05) {
  cat("Остатки нормальны — условие выполняется.\n")
} else {
  cat("Остатки НЕ нормальны — условие нарушено.\n")
}

#p-value = 0.67, это больше 0.05 — остатки нормальные, значит модель ошибается без закономерности и её ошибки случайны и некритичны (где-то переоценила, где-то недооценила).

#График по итогам теста Шапиро, что б визуализировать данные
par(mfrow = c(2, 2))
plot(model)
par(mfrow = c(1, 1))

# ЧТО ВИЖУ НА ЭТИХ ГРАФИКАХ:
#- Residuals vs Fitted (первый): точки разбросаны ровно, нет такого что слева всё узко, а справа широко (это называется "воронка"). Значит дисперсия постоянная — ок.
#- Q-Q plot (второй): точки идут вдоль прямой. Ещё одно подтверждение, что остатки нормальные.
#- Scale-Location и Residuals vs Leverage: без критических выбросов.



# ========== 3. ЛИНИЯ РЕГРЕССИИ С ДОВЕРИТЕЛЬНОЙ ОБЛАСТЬЮ ==========
#Создаю новые значения Petal.Length для предсказания
new_x <- seq(
  min(iris_versicolor$Petal.Length),
  max(iris_versicolor$Petal.Length),
  length.out = 100
)

#Предсказываю Sepal.Length и доверительный интервал
pred <- predict(model, newdata = data.frame(Petal.Length = new_x),
                interval = "confidence")

#Повторяю график, что б теперь дополнить его полученными результатами
plot(
  iris_versicolor$Petal.Length,
  iris_versicolor$Sepal.Length,
  xlab = "Длина лепестка (Petal.Length)",
  ylab = "Длина чашелистика (Sepal.Length)",
  main = "Versicolor: линейная регрессия с 95% доверительной областью",
  pch = 19,
  col = "purple"
)

#Добавляю линию регрессии (предсказания модели)
lines(new_x, pred[, "fit"], col = "red", lwd = 2)

#Добавляю доверительную область (где с 95% вероятностью лежит настоящая линия)
lines(new_x, pred[, "lwr"], col = "red", lty = 2, lwd = 1.5)
lines(new_x, pred[, "upr"], col = "red", lty = 2, lwd = 1.5)

#Легенда (пометка для себя — легендой называют расшифровку обозначений на графике)
legend("topleft",
       legend = c("Наблюдения", "Линия регрессии", "95% доверительная область"),
       col = c("purple", "red", "red"),
       pch = c(19, NA, NA),
       lty = c(NA, 1, 2),
       lwd = c(NA, 2, 1.5))

# ЧТО ВИЖУ НА ГРАФИКЕ:
#- Красная линия проходит прямо сквозь кучу точек — модель легла хорошо.
#- Красный пунктир — это доверительная область. В центре она узкая (много точек - точнее предсказание), по краям расширяется (мало точек - сомневаемся).
#- С вероятностью 95% настоящая линия регрессии лежит где-то внутри этих пунктирных линий.



# ========== 4. ПРЕДСКАЗАНИЕ ДЛЯ 30% И 99% ПЕРЦЕНТИЛЕЙ ==========
#Нахожу 30% и 99% перцентили Petal.Length
p30 <- quantile(iris_versicolor$Petal.Length, 0.30)
p99 <- quantile(iris_versicolor$Petal.Length, 0.99)

cat("\n=== ПРЕДСКАЗАНИЯ ===\n")
cat("30% перцентиль Petal.Length =", round(p30, 2), "\n")
cat("99% перцентиль Petal.Length =", round(p99, 2), "\n")

#Предсказываю значения Sepal.Length
pred_p30 <- predict(model, newdata = data.frame(Petal.Length = p30),
                    interval = "confidence")
pred_p99 <- predict(model, newdata = data.frame(Petal.Length = p99),
                    interval = "confidence")

cat("\nДля Petal.Length =", round(p30, 2), "(30% перцентиль):\n")
cat("  Предсказанный Sepal.Length =", round(pred_p30[, "fit"], 2), "\n")
cat("  95% ДИ = [", round(pred_p30[, "lwr"], 2), ", ", round(pred_p30[, "upr"], 2), "]\n")

cat("\nДля Petal.Length =", round(p99, 2), "(99% перцентиль):\n")
cat("  Предсказанный Sepal.Length =", round(pred_p99[, "fit"], 2), "\n")
cat("  95% ДИ = [", round(pred_p99[, "lwr"], 2), ", ", round(pred_p99[, "upr"], 2), "]\n")

# ЧТО ТАКОЕ ПЕРЦЕНТИЛИ:
#30% перцентиль — значение, ниже которого 30% всех лепестков. То есть почти треть растений с короткими лепестками.
#99% перцентиль — почти максимум, только 1% растений имеет лепесток ещё длиннее.
# ЧТО ВИЖУ В ПРЕДСКАЗАНИЯХ:
#Для короткого лепестка (30%) чашелистик предсказуемо короткий, для длинного (99%) — длинный. Всё логично, связь положительная.
#Доверительный интервал говорит: с вероятностью 95% средняя длина чашелистика для такого лепестка будет в этих пределах.



# ========== ВЫВОД ПО ЛИНЕЙНОЙ МОДЕЛИ ==========

#1. УРАВНЕНИЕ: Sepal.Length = 2.41 + 0.83 * Petal.Length
#Если лепесток станет на 1 см длиннее, чашелистик в среднем вырастет на 0.83 см.

#2. ЗНАЧИМОСТЬ: p-value = 2.59e-10, это очень мало. Длина лепестка влияет на длину чашелистика.

#3. КАЧЕСТВО МОДЕЛИ: R-squared = 0.57. Модель объясняет 57% разброса в длине чашелистиков. Это больше половины. Остальные 43% объясняются другими факторами, которые не учтены в модели (освещение, влажность, возраст растения и т.д.)

#4. ПРОВЕРКА УСЛОВИЙ:
#Тест Шапиро-Уилка показал p-value = 0.67 (> 0.05), дисперсия постоянная (на графиках всё ровно). Модели можно верить.

#5. ИТОГ: у versicolor чем длиннее лепесток, тем длиннее чашелистик. Зная длину лепестка, можно довольно точно прикинуть длину чашелистика по формуле.