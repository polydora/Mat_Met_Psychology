# ========== ЗАГРУЗКА ДАННЫХ ==========
#Рост эльфов из нашего отряда (см)
elves <- c(180, 180, 171, 176, 187, 183, 184, 174, 185, 180, 176, 177, 183, 176, 170)
#Рост неизвестных фигур (см)
strangers <- c(195, 189, 198, 185, 188, 189, 174, 190, 203, 184, 188, 190, 185, 189, 191, 181, 184, 190, 186)

#Теперь нужно вычислить среднее арифметическое, ну и +сохранить результат в переменную, что б не усложнять себе жизнь дальше. Для вывода текста в консоль я использую команду concatenate (cat), потому что так выходит красивее и она мне очень нравиться.
# ========== СЧИТАЕМ СРЕДНИЕ ==========
mean_elves <- mean(elves)
mean_strangers <- mean(strangers)

cat("Средний рост эльфов:", round(mean_elves, 1), "см\n")
cat("Средний рост неизвестных фигур:", round(mean_strangers, 1), "см\n")


# ========== ГИПОТЕЗЫ ==========
#H0: Неизвестные это ЭЛЬФЫ (рост неизвестных фигур НЕ отличается от роста эльфов)
#H1: Неизвестные это ЧУЖИЕ (рост неизвестных фигур ОТЛИЧАЕТСЯ от роста эльфов)

#Теперь можно проводить тест и выводить результат
# ========== ТЕСТ СТЬЮДЕНТА ==========
test <- t.test(strangers, elves)

# ========== РЕЗУЛЬТАТ ==========
cat("p-value =", test$p.value, "\n")

if (test$p.value < 0.05) {
  cat("p-value меньше 0.05, значит ОТКЛОНЯЕМ H0.\n")
  cat("ВЫВОД: Это ЧУЖИЕ!\n")
} else {
  cat("p-value больше 0.05, значит ПРИНИМАЕМ H0.\n")
  cat("ВЫВОД: Это СВОИ (эльфы)!\n")
}


#Оформляем результат в красивый график!
# ========== ГРАФИК ==========
means <- c(mean_elves, mean_strangers)
names(means) <- c("Эльфы", "Неизвестные")

barplot(
  means,
  col = c("lightblue", "firebrick"),
  ylim = c(0, 210),
  ylab = "Средний рост (см)",
  main = "Сравнение роста"
)


