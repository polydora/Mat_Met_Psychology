# ========== ЗАГРУЗКА ДАННЫХ ==========
install.packages("DAAG")
library(DAAG)
data(rice)


#Смотрим структуру данных и первые строки, чтобы убедиться, что данные загрузились корректно и переменные правильного типа для ANOVA
str(rice)
head(rice)

# ========== ПЕРЕМЕННЫЕ ==========
#shoots_dry - сухая масса побегов (зависимая переменная)
#variety    - сорт риса (фактор: wt и ANU843)
#fert       - удобрения (фактор: F10, NH4Cl, NH4NO3)

# ========== ДВУХФАКТОРНЫЙ ANOVA ==========
#H0: Сухая масса побегов НЕ зависит от сорта, удобрений и их взаимодействия
#H1: Сухая масса побегов зависит хотя бы от одного из этих факторов

#Делаю все тоже, что в прошлой дз, не буду повторно всё описывать
anova_result <- aov(ShootDryMass ~ variety * fert, data = rice)
cat("=== РЕЗУЛЬТАТ ДВУХФАКТОРНОГО ANOVA ===\n")
summary(anova_result)

#Нормальность остатков
residuals <- residuals(anova_result)
cat("\n=== ПРОВЕРКА НОРМАЛЬНОСТИ ОСТАТКОВ ===\n")
shapiro.test(residuals)

#Графики остатков
par(mfrow = c(2, 2))
plot(anova_result)
par(mfrow = c(1, 1))

# ========== ГРАФИК (ВЗАИМОДЕЙСТВИЕ ФАКТОРОВ) ==========
interaction.plot(
  x.factor = rice$fert,
  trace.factor = rice$variety,
  response = rice$ShootDryMass,
  col = c("blue", "red"),
  lwd = 2,
  xlab = "Удобрения",
  ylab = "Средняя сухая масса побегов",
  trace.label = "Сорт",
  main = "Взаимодействие: Сорт × Удобрения"
)




# ========== ВЫВОД ==========

#1. ВЛИЯНИЕ СОРТА (variety): p-value = 5.86e-11 (это очень мало, < 0.05) 
#Сорт риса ЗНАЧИМО влияет на сухую массу побегов. Разные сорта дают разную массу побегов.

#2. ВЛИЯНИЕ УДОБРЕНИЙ (fert): p-value = 0.00025 (< 0.05) 
#Удобрения ЗНАЧИМО влияют на сухую массу побегов. При разных удобрениях масса побегов разная.

#3. ВЗАИМОДЕЙСТВИЕ СОРТА И УДОБРЕНИЙ (variety:fert): p-value = 2.88e-14 (< 0.05) 
#Взаимодействие ЗНАЧИМО. Это значит, что удобрения действуют ПО-РАЗНОМУ на разные сорта риса. Нельзя сказать, что какое-то удобрение лучше для всех сортов — всё зависит от конкретного сорта.

#4. ПРОВЕРКА УСЛОВИЙ ANOVA:
#Тест Шапиро-Уилка показал p-value = 0.033 (< 0.05). 
#Остатки НЕ нормальны. Условие ANOVA формально нарушено. Но как и в прошлом дз, при достаточном количестве данных это не страшно. К тому же p-value очень малы (далеко от 0.05), поэтому выводы можно считать надёжными, несмотря на отклонение от нормальности.

#5. РАСШИФРОВКА ГРАФИКА ВЗАИМОДЕЙСТВИЯ:
#Красная линия это сорт ANU843, синяя линия это сорт wt. Обе линии начинаютьтся на противоположных значениях, что значит что удобрение F10 на них влияет по разному. 
#Между F10 и NH4Cl линии пересекаются — это говорит о сильном взаимодействии: удобрение F10 действует совершенно по-разному. Сорт wt на F10 даёт высокую массу побегов, а сорт ANU843 на том же F10 — низкую.
#После пересечения обе линии идут вверх — удобрение NH4NO3 даёт высокую массу для ОБОИХ сортов.
#Практический вывод: если нужно получить максимум массы побегов, для сорта wt можно использовать F10 или NH4NO3, а для сорта ANU843 лучше всего подходит NH4NO3.

#ОБЩИЙ ИТОГ:
#Сухая масса побегов риса зависит И от сорта, И от удобрений, и от их взаимодействия. Это означает, что для получения максимальной массы побегов нужно подбирать удобрение ПОД КОНКРЕТНЫЙ СОРТ, а не использовать одно и то же для всех.