# ========== ЗАГРУЗКА ДАННЫХ ==========
data <- read_excel("C:/MatMet_MIP_2026/Data/hydrology_2022 (1).xls")

#RStudio не может нормально прочитать файл из-за наличия в колонке Air_T значений NA, поэтому нужно преобразровать его в число
data$Air_T <- as.numeric(data$Air_T)

#Теперь можно убрать NA и оставить только летние месяцы и значения температуры
data_summer <- data[data$Month %in% c("June", "July", "August") & !is.na(data$Air_T), ]

#По старинке превращаем Month в фактор, что б потом не мучаться с повторами. Можно заметить что я добавила as.factor, чего не делала в прошглой дз. Это из-за того, что там была команда mean, она считает средне арифметическое, а здесь мы работаем с AVONA, которая разбивает написанное по категориям игруппам. Сейчас нам нужна группа месяцев
data_summer$Month <- as.factor(data_summer$Month)

#Теперь наглядно смотрим, сколько данных в каждом месяце
boxplot(Air_T ~ Month, data = data_summer,
        main = "Температура воздуха по месяцам",
        xlab = "Месяц", ylab = "Температура (°C)",
        col = c("lightblue", "lightgreen", "salmon"))


# ========== ГИПОТЕЗЫ ==========
#H0: средняя температура одинакова во всех трёх месяцах
#H1: хотя бы в одном месяце средняя температура отличается

#Анализируем зависимсть температуры от месяца с помощью таблицы и выводим это красиво в environment.
anova_result <- aov(Air_T ~ Month, data = data_summer)
summary(anova_result)

#Достаём и проверяем остатки. Не сразу поняла что это, но в итоге разобралась. Остатки это разница между наблюдаемым и предсказываемым моделью. Если остатки привышают норму, то данные не подходят для метода ANOVA
residuals <- residuals(anova_result)
shapiro.test(residuals)

#Графики остатков
par(mfrow = c(1, 2))
qqnorm(residuals, main = "Q-Q plot остатков")
qqline(residuals, col = "red")
plot(fitted(anova_result), residuals, main = "Остатки vs предсказанные")
abline(h = 0, col = "red")
par(mfrow = c(1, 1))

# ========== ТЕСТ ТЬЮКИ ==========
TukeyHSD(anova_result)

# ========== ГРАФИК ==========
#Считаем средние для каждого месяца
means <- tapply(data_summer$Air_T, data_summer$Month, mean)

#Рисуем столбики мои столбики..
barplot(means,
        col = c("gold", "coral", "steelblue"),
        main = "Средняя температура воздуха",
        ylab = "Температура (°C)",
        ylim = c(0, 20))




