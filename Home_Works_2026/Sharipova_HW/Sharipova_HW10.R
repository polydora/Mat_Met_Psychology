#Считаю крестики и нолики для каждого дня
x_count <- numeric(30)  #пустой вектор под крестики
o_count <- numeric(30)  #пустой вектор под нолики

for (i in 1:30) {
  chars <- strsplit(raw[i], "")[[1]]  #разбиваю строку на символы
  x_count[i] <- sum(chars == "x")     #считаю крестики
  o_count[i] <- sum(chars == "0")     #считаю нолики (это нули в записи)
}

#Собираю всё в одну таблицу
df <- data.frame(
  day = 1:30,
  temp = temp,
  x = x_count,
  o = o_count
)

#Смотрю, что получилось
