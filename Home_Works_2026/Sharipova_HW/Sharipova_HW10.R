# ========== 1. ЛИНЕЙНАЯ МОДЕЛЬ ==========
#Пытаюсь объяснить число крестиков через число ноликов и температуру
model <- lm(x ~ o + temp, data = df)

cat("\n=== РЕЗУЛЬТАТЫ МОДЕЛИ ===\n")
summary(model)

# ЧТО ВИЖУ:
#Смотрю на p-value для o и для temp. Если меньше 0.05 — этот фактор важен.
#Смотрю на Multiple R-squared — сколько процентов изменчивости объясняет модель.


# ========== 2. ДИАГНОСТИКА МОДЕЛИ ==========

cat("\n=== ПРОВЕРКА ОСТАТКОВ ===\n")
residuals <- residuals(model)

#Нормальность остатков
shapiro_test <- shapiro.test(residuals)
cat("Тест Шапиро-Уилка: p-value =", shapiro_test$p.value, "\n")
if (shapiro_test$p.value > 0.05) {
  cat("Остатки нормальные — ок.\n")
} else {
