#Это функция для анализа, она объединяет все шаги анализа, что бы не размножать код одинаковыми шагами
check_normality <- function(x, var_name) {
  cat("\n==================== ", var_name, " ====================\n")
  
  x <- na.omit(x)
  n <- length(x)
  
  cat("Количество наблюдений:", n, "\n")
  
  if(n < 3) {
    cat("ВЫВОД: Слишком мало данных для теста Шапиро-Уилка (нужно >= 3)\n")
    return()
  }
  
  if(n > 5000) {
    cat("ВЫВОД: Слишком много данных для теста Шапиро-Уилка (нужно <= 5000)\n")
    cat("Используем тест Андерсона-Дарлинга\n")
    library(nortest)
    ad_test <- ad.test(x)
    cat("p-value (Андерсон-Дарлинг):", ad_test$p.value, "\n")
    if(ad_test$p.value > 0.05) {
      cat("ВЫВОД: Распределение НЕ отличается от нормального (p > 0.05)\n")
    } else {
      cat("ВЫВОД: Распределение ОТЛИЧАЕТСЯ от нормального (p < 0.05)\n")
    }
    return()
  }
  
#Т.к. данные в порядке, можно считать статисктику и проводить тест
  cat("Среднее:", round(mean(x), 3), "\n")
  cat("Стд. отклонение:", round(sd(x), 3), "\n")
  cat("Асимметрия (skewness):", round(skewness(x), 3), "\n")
  cat("Эксцесс (kurtosis):", round(kurtosis(x), 3), "\n")
  
#Провожу тест Шапиро
  shapiro_test <- shapiro.test(x)
  cat("p-value (Шапиро-Уилк):", shapiro_test$p.value, "\n")
  
  if(shapiro_test$p.value > 0.05) {
    cat("ВЫВОД: Распределение НЕ отличается от нормального (p > 0.05)\n")
  } else {
    cat("ВЫВОД: Распределение ОТЛИЧАЕТСЯ от нормального (p < 0.05)\n")
  }
}

#Теперь просто анализируем каждую колонку
for (i in 1:ncol(data)) {
  check_normality(data[[i]], colnames(data)[i])
}

