#Опять датасет и 21 день
data(ChickWeight)
chick_day21 <- ChickWeight[ChickWeight$Time == 21, ]

#Нужен список диет
diets <- levels(chick_day21$Diet)

#Теперь надо создать пустой датафрейм для результатов. Дальше я положилась на ИИ, т.к. стала плохо понимать что от меня требуется
result <- data.frame(
  Diet = character(),
  n = numeric(),           # объём выборки
  Mean = numeric(),        # среднее
  SD = numeric(),          # стандартное отклонение
  SE = numeric(),          # стандартная ошибка среднего
  t_crit = numeric(),      # критическое значение t
  CI_lower = numeric(),    # нижняя граница ДИ
  CI_upper = numeric(),    # верхняя граница ДИ
  stringsAsFactors = FALSE
)

#Считаем для каждой диеты
for (diet in diets) {
  
#Мне нужно выбрать данные для конкретной диеты
  x <- chick_day21$weight[chick_day21$Diet == diet]
  
#Объём выборки
  n <- length(x)
  
#Выборочное среднее
  mean_x <- mean(x)
  
#Стандартное отклонение
  sd_x <- sd(x)
  
#Стандартная ошибка среднего: SE = sd / sqrt(n)
  se_x <- sd_x / sqrt(n)
  
#Степени свободы: df = n - 1
  df <- n - 1
  
#Критическое значение t для 95% доверительного интервала qt(0.975, df) — это 97.5% квантиль t-распределения (потому что 2.5% слева + 95% в центре = 97.5% справа)  (комментарий от ИИ для пояснения, но я все-равно не поняла)
  t_crit <- qt(0.975, df)
  
#Границы доверительного интервала: mean ± t_crit * SE
  ci_lower <- mean_x - t_crit * se_x
  ci_upper <- mean_x + t_crit * se_x
  
#Добавляем строку в таблицу
  result <- rbind(result, data.frame(
    Diet = diet,
    n = n,
    Mean = round(mean_x, 2),
    SD = round(sd_x, 2),
    SE = round(se_x, 2),
    t_crit = round(t_crit, 3),
    CI_lower = round(ci_lower, 2),
    CI_upper = round(ci_upper, 2)
  ))
}

#Теперь нужно вывести итоговую таблицу и интерпретацию
print("=== 95% ДОВЕРИТЕЛЬНЫЕ ИНТЕРВАЛЫ ДЛЯ ВЕСА ЦЫПЛЯТ (21-й день) ===")
print(result)

cat("\n=== ИНТЕРПРЕТАЦИЯ ===\n")
